import React from "react";
import ReactDOM from "react-dom";
import { Provider } from "react-redux";
import { createStore, applyMiddleware } from "redux";
import thunk from "redux-thunk";

import reducers from "./Reducers";

import App from "./Components/App";
// ref-2 signle track for singlese pages
let hideTrackButtons = document.querySelector("#root").getAttribute("hidetrackribbon") === "true";
const show = document.querySelector("#root").getAttribute("show");

let parameters = null;

//Get url parameters
if (window.location.href.includes("?")) {
    const queryString = window.location.search
 if (queryString==="?"){
    parameters = window.location.href.split("?")[1];
    parameters = parameters.split("&");
    parameters = parameters.map(param => param.split("="));
    if (parameters.find(([name, value]) => name === "track" && show === "BRE")) {
        hideTrackButtons = true;
    }
}
}else{
    null
}

const speakerAgendaLinks = document.querySelector("#root").getAttribute("speakeragendalinks") === "true";

/**
 * Building an options object from the root element generated by MODx
 */
const options = {
    conf: document.querySelector("#root").getAttribute("conf"),
    show: document.querySelector("#root").getAttribute("show"),
    reglink: document.querySelector("#root").getAttribute("reglink"),
    reginterest: document.querySelector("#root").getAttribute("reginterest"),
    event: document.querySelector("#root").getAttribute("event"),
    topNav: document.querySelector("#root").getAttribute("topnav") === "true",
    hideTrackButtons,
    hideDownloadLink: document.querySelector("#root").getAttribute("hidedownloadlink") === "true",
    hideTrackRibbon: document.querySelector("#root").getAttribute("hidetrackribbon") === "true",
    contactcampaign: document.querySelector("#root").getAttribute("contactcampaign"),
    continent: document.querySelector("#root").getAttribute("continent"),
    mode: document.querySelector("#root").getAttribute("mode"), //What confman mode shall we start in IE Full agenda, Speaker List
    downloadagenda: document.querySelector("#root").getAttribute("downloadagenda"),
    generalenquiry: document.querySelector("#root").getAttribute("generalenquiry"),
    convincepdf: document.querySelector("#root").getAttribute("convincepdf"),
    ondemand: JSON.parse(document.querySelector("#root").getAttribute("ondemand")),
    fullagendalocation: document.querySelector("#root").getAttribute("fullagendalocation"),
    speakerAgendaLinks,
    extraMode: document.querySelector("#root").getAttribute("extramode") != undefined ? document.querySelector("#root").getAttribute("extramode") : false,
    additionalfilters:
        document.querySelector("#root").getAttribute("additionalfilters") != undefined
            ? document.querySelector("#root").getAttribute("additionalfilters").split(" | ")
            : false, //String Constant list of extra filters delimited by |
    daynameoverride:
        document.querySelector("#root").getAttribute("daynameoverride") != ""
            ? document.querySelector("#root").getAttribute("daynameoverride").split(" | ")
            : undefined, //Overrides for day names on the agenda nav menu, delimited by |
    parameters,
    cocktailMaxTagSelection: document.querySelector("#root").getAttribute("cocktailMaxTagSelection"), //set the minimun number of selectable tags to more to next step
// Ref2 createing a new option to trigger what we need ->checkbox
    showsinglesetrack:document.querySelector("#root").getAttribute("showsinglesetrack"),
};

//Fix for test websites
if (options.show.includes("-Test")) {
    options.show = options.show.replace("-Test", "");
}

//Create a redux store (some docs like to confusingly call this state) using our reducers, and bonus middleware (thunk) which lets us use asynchronous action creators for things like api calls.
const store = createStore(reducers, applyMiddleware(thunk));

ReactDOM.render(
    //Wrap the App in a Provider component that redux provides which provides the store to our app.
    <Provider store={store}>
        <App initOptions={options} /> {/* Load  the app with the options object we've created*/}
    </Provider>,
    document.querySelector("#root")
);
